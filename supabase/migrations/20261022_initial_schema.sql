-- Habilitar extensión para identificadores universales si se requiere
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ----------------------------------------------------------------------------
-- 1. Tabla de Telemetría Fisiológica: measurements
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.measurements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id TEXT NOT NULL,
    heart_rate INTEGER NOT NULL CHECK (heart_rate >= 20 AND heart_rate <= 300),
    spo2 DOUBLE PRECISION NOT NULL CHECK (spo2 >= 50.0 AND spo2 <= 100.0),
    temperature DOUBLE PRECISION NOT NULL CHECK (temperature >= 30.0 AND temperature <= 45.0),
    activity TEXT NOT NULL,
    measured_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Índices de alto rendimiento para consultas de series de tiempo
CREATE INDEX IF NOT EXISTS idx_measurements_device_id ON public.measurements(device_id);
CREATE INDEX IF NOT EXISTS idx_measurements_measured_at ON public.measurements(measured_at DESC);
CREATE INDEX IF NOT EXISTS idx_measurements_composite ON public.measurements(device_id, measured_at DESC);

-- ----------------------------------------------------------------------------
-- 2. Tabla de Eventos de Alerta y Detección de Anomalías: alerts
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    measurement_id BIGINT REFERENCES public.measurements(id) ON DELETE SET NULL,
    severity TEXT NOT NULL CHECK (severity IN ('normal', 'warning', 'critical')),
    message TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_alerts_measurement_id ON public.alerts(measurement_id);
CREATE INDEX IF NOT EXISTS idx_alerts_severity ON public.alerts(severity);
CREATE INDEX IF NOT EXISTS idx_alerts_created_at ON public.alerts(created_at DESC);

-- ----------------------------------------------------------------------------
-- 3. Configuración de Seguridad por Filas (Row Level Security - RLS)
-- ----------------------------------------------------------------------------
ALTER TABLE public.measurements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alerts ENABLE ROW LEVEL SECURITY;

-- Política de acceso exclusivo para backend autorizado y service_role
CREATE POLICY "Permitir acceso completo a roles administrativos del backend"
    ON public.measurements
    FOR ALL
    TO postgres, service_role
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Permitir acceso completo a alertas para roles del backend"
    ON public.alerts
    FOR ALL
    TO postgres, service_role
    USING (true)
    WITH CHECK (true);
